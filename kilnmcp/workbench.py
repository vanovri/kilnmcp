def evaluate_lampung_batch(preset: str = "nominal", cfg: SimConfig | None = None) -> dict:
    """Run deterministic simulation, rule+EWMA detection, UART framing, carbon math, and bag reconciliation."""
    if cfg is None:
        cfg = lampung_config(preset=preset)
    p_meta = LAMPUNG_FAULT_PRESETS.get(preset, LAMPUNG_FAULT_PRESETS["nominal"])
    rows = list(simulate(cfg))
    readings: dict[str, list[list[float]]] = {}
    for ts, s, v in rows:
        readings.setdefault(s, []).append([ts, v])

    ts_list = [pt[0] for pt in readings["temp_c"]]
    min_list = [round((t - ts_list[0]) / 60.0, 2) for t in ts_list]
    temp_vals = [pt[1] for pt in readings["temp_c"]]
    o2_vals = [pt[1] for pt in readings["o2_pct"]]
    moist_vals = [pt[1] for pt in readings["moisture_pct"]]
    mass_vals = [pt[1] for pt in readings["mass_kg"]]

    start_ts, end_ts = ts_list[0], ts_list[-1]
    warmup_min = THRESH_CFG.get("warmup_minutes", 20)
    cooldown_min = THRESH_CFG.get("cooldown_minutes", 15)
    steady_lo_idx = int(warmup_min * 60 / cfg.step_s)
    steady_hi_idx = int((cfg.duration_min - cooldown_min) * 60 / cfg.step_s)

    ewma_t_mean, ewma_t_hi, ewma_t_lo = _compute_ewma_series(temp_vals, steady_lo_idx, steady_hi_idx)
    ewma_o2_mean, ewma_o2_hi, _ = _compute_ewma_series(o2_vals, steady_lo_idx, steady_hi_idx)

    raw_events = detect(readings, THRESH_CFG, start_ts, end_ts, step_s=cfg.step_s)
    anomalies = []
    for idx, ev in enumerate(raw_events, 1):
        diag = _diagnose_rule(ev["rule"])
        anomalies.append({
            "id": idx,
            **ev,
            "start_min": round((ev["ts"] - start_ts) / 60.0, 2),
            "end_min": round((ev["end_ts"] - start_ts) / 60.0, 2),
            "start_iso": iso(ev["ts"]),
            "end_iso": iso(ev["end_ts"]),
            "diagnosis": diag,
        })

    steady_temps = temp_vals[steady_lo_idx : steady_hi_idx + 1]
    steady_o2 = o2_vals[steady_lo_idx : steady_hi_idx + 1]
    steady_moist = moist_vals[steady_lo_idx : steady_hi_idx + 1]
    in_zone = sum(1 for t in steady_temps if 450.0 <= t <= 650.0)
    steady_metrics = {
        "temp_min_c": round(min(steady_temps), 2),
        "temp_mean_c": round(sum(steady_temps) / len(steady_temps), 2),
        "temp_max_c": round(max(steady_temps), 2),
        "in_target_zone_pct": round(in_zone / len(steady_temps) * 100.0, 1),
        "o2_max_pct": round(max(steady_o2), 3),
        "moisture_max_pct": round(max(steady_moist), 2),
    }

    output_mass_kg = mass_vals[-1]
    h_c_org_molar = float(p_meta.get("h_c_org_molar", 0.42))
    carbon = compute_lampung_carbon(output_mass_kg, c_org_frac=0.70, h_c_org_molar=h_c_org_molar)
    bags_by_mode = {
        mode: reconcile_lampung_bags(cfg.batch_id, output_mass_kg, cfg.input_mass_kg, bag_mode=mode)
        for mode in ("mixed", "50kg", "25kg")
    }

    # Build representative UART frame stream samples (every 2 minutes + anomaly peak frames)
    anomaly_ts_set = set()
    for a in anomalies:
        anomaly_ts_set.add(a["ts"])
        anomaly_ts_set.add(a["end_ts"])
    uart_frames = []
    for step_i, ts in enumerate(ts_list):
        is_anom_ts = ts in anomaly_ts_set or any(a["ts"] <= ts <= a["end_ts"] for a in anomalies)
        if step_i % 12 == 0 or step_i == len(ts_list) - 1 or (is_anom_ts and step_i % 3 == 0):
            for s_name, arr in (("temp_c", temp_vals), ("o2_pct", o2_vals), ("moisture_pct", moist_vals), ("mass_kg", mass_vals)):
                raw_frame = uart.encode(cfg.batch_id, ts, s_name, arr[step_i]).decode("ascii").strip()
                body, chk = raw_frame[1:].rsplit("*", 1)
                uart_frames.append({
                    "step": step_i,
                    "min": min_list[step_i],
                    "ts": int(ts),
                    "sensor": s_name,
                    "value": arr[step_i],
                    "frame": raw_frame,
                    "checksum": chk,
                    "in_anomaly_window": is_anom_ts,
                })

    if not anomalies:
        quality_gate = "PASS_DRAFT_CRITERIA"
    elif any(a["rule"] == "R-O2-HIGH" for a in anomalies):
        quality_gate = "QUARANTINE_OXIDATION_RISK"
    elif any(a["rule"] == "R-MOIST-HIGH" for a in anomalies):
        quality_gate = "HOLD_FOR_LAB_HC_ASSAY"
    else:
        quality_gate = "HOLD_TELEMETRY_SENSOR_AUDIT"

    bundle = {
        "synthetic": True,
        "certification_status": CERTIFICATION_STATUS,
        "banner": SYNTHETIC_BANNER,
        "preset_id": preset,
        "label": p_meta["label"],
        "batch_id": cfg.batch_id,
        "seed": cfg.seed,
        "feedstock": cfg.feedstock,
        "feedstock_blend": LAMPUNG_FEEDSTOCK_BLEND,
        "target_temp_zone_c": [450.0, 650.0],
        "nominal_temp_c": cfg.target_temp_c,
        "duration_min": cfg.duration_min,
        "step_s": cfg.step_s,
        "start_ts": start_ts,
        "end_ts": end_ts,
        "start_iso": iso(start_ts),
        "end_iso": iso(end_ts),
        "input_mass_kg": cfg.input_mass_kg,
        "output_mass_kg": output_mass_kg,
        "yield_frac_target": cfg.yield_frac,
        "quality_gate": quality_gate,
        "steady_metrics": steady_metrics,
        "anomalies": anomalies,
        "carbon_accounting": carbon,
        "bag_reconciliation": bags_by_mode["mixed"],
        "bag_reconciliation_by_mode": bags_by_mode,
        "uart_stats": {
            "total_frames": len(rows),
            "sampled_frames": len(uart_frames),
            "ok": len(rows),
            "bad": 0,
            "baud": 115200,
            "protocol": "$KILN,<batch_id>,<ts>,<sensor>,<value>*<XOR>\\r\\n",
        },
        "uart_frames": uart_frames,
        "series": {
            "ts": ts_list,
            "min": min_list,
            "temp_c": temp_vals,
            "o2_pct": o2_vals,
            "moisture_pct": moist_vals,
            "mass_kg": mass_vals,
            "ewma_temp_mean": ewma_t_mean,
            "ewma_temp_upper": ewma_t_hi,
            "ewma_temp_lower": ewma_t_lo,
            "ewma_o2_mean": ewma_o2_mean,
            "ewma_o2_upper": ewma_o2_hi,
        },
    }
    bundle["markdown_report"] = build_markdown_report(bundle, bag_mode="mixed")
    return bundle


def build_all_scenarios() -> dict[str, dict]:
    return {preset: evaluate_lampung_batch(preset) for preset in LAMPUNG_FAULT_PRESETS}


