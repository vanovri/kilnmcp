def _diagnose_rule(rule: str) -> dict[str, str]:
    if "O2-HIGH" in rule or "o2_pct" in rule:
        return {
            "probable_cause": "air_leak",
            "explanation": (
                "Flue O2 proxy exceeded 5.0% threshold concurrent with a >130 °C reactor temperature drop, "
                "indicating air ingress through primary kiln door gasket or quench port seal."
            ),
            "suggested_action": (
                "Inspect and reseal retort door gasket, verify secondary air damper position, and quarantine "
                "partially oxidized char fraction for ash/C_org lab re-assay."
            ),
        }
    if "MOIST-HIGH" in rule or "moisture" in rule:
        return {
            "probable_cause": "wet_feedstock",
            "explanation": (
                "Feedstock moisture proxy rose above 20.0% MC (peaking at 28.0%) with a simultaneous ~90 °C "
                "endothermic dip below 500 °C, consistent with un-dried coffee parchment/husk pocket."
            ),
            "suggested_action": (
                "Pre-dry coffee-shell + corn-cob blend on solar drying floor to <15% MC before charging; "
                "hold batch for molar H/C_org laboratory verification (<0.70 threshold)."
            ),
        }
    if "STUCK" in rule:
        return {
            "probable_cause": "sensor_fault",
            "explanation": (
                "Primary K-type thermocouple (temp_c) exhibited zero-variance flatline across >=6 consecutive "
                "10-second frames during steady pyrolysis, indicating a latched ADC channel or open junction."
            ),
            "suggested_action": (
                "Cross-check against secondary flue thermocouple log, inspect MAX31855 cold-junction SPI bus, "
                "and mark telemetry window as sensor-fault audited in draft dMRV packet."
            ),
        }
    return {
        "probable_cause": "thermal_excursion",
        "explanation": "Reactor temperature deviated outside steady EWMA / threshold envelope during active pyrolysis.",
        "suggested_action": "Review syngas recycle air ratio and verify feedstock blend uniformity.",
    }


def _compute_ewma_series(values: list[float], start_idx: int, end_idx: int, alpha: float = 0.1, k_sigma: float = 4.0, min_samples: int = 30):
    means: list[float] = []
    uppers: list[float] = []
    lowers: list[float] = []
    mean = None
    var = 0.0
    n = 0
    for i, v in enumerate(values):
        if mean is None:
            mean = v
            var = 0.0
        sd = var ** 0.5
        in_steady = start_idx <= i <= end_idx
        is_hit = in_steady and n >= min_samples and sd > 0 and abs(v - mean) > k_sigma * sd
        means.append(round(mean, 2))
        uppers.append(round(mean + k_sigma * sd, 2))
        lowers.append(round(max(0.0, mean - k_sigma * sd), 2))
        if not is_hit:
            d = v - mean
            mean += alpha * d
            var = (1.0 - alpha) * (var + alpha * d * d)
        n += 1
    return means, uppers, lowers


