def render_workbench_html() -> str:
    scenarios = build_all_scenarios()
    embedded_json = json.dumps(scenarios, separators=(",", ":"))
    return WORKBENCH_HTML_TEMPLATE.replace("__EMBEDDED_SCENARIOS_JSON__", embedded_json)


def write_workbench(
    out_path: str | Path | None = None,
    mirror_paths: list[str | Path] | None = None,
) -> list[str]:
    html = render_workbench_html()
    primary = Path(out_path) if out_path else (ROOT / "web" / "index.html")
    primary.parent.mkdir(parents=True, exist_ok=True)
    primary.write_text(html, encoding="utf-8")
    written = [str(primary)]
    for mp in mirror_paths or []:
        p = Path(mp)
        p.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(primary, p)
        written.append(str(p))
    return written


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate ENVIID × KilnMCP Lampung Pyrolysis Workbench HTML")
    ap.add_argument("--out", default=str(ROOT / "web" / "index.html"))
    ap.add_argument("--mirror", action="append", default=[])
    a = ap.parse_args(argv)
    paths = write_workbench(a.out, a.mirror)
    for p in paths:
        print(f"[workbench] wrote {p}")
    return paths


if __name__ == "__main__":
    main()
